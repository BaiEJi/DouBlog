  for(const id of created) {try {const map=await api('GET',`/api/mindmap/maps/${id}`);await api('DELETE',`/api/mindmap/maps/${id}`,{revision:map.revision,mutation_id:crypto.randomUUID()})}catch{/* preserve failing test evidence */}}
